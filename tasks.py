"""Forty deterministic Mini Lab tasks and their reference actions."""

from dataclasses import dataclass
from typing import Any, Dict, List


@dataclass(frozen=True)
class Task:
    id: str
    instruction: str
    success: str
    files: Dict[str, str]
    rules: List[Dict[str, Any]]
    reference: List[Dict[str, Any]]
    max_steps: int = 12


def action(tool: str, **args: Any) -> Dict[str, Any]:
    return {"tool": tool, "args": args}


def submit(value: Any) -> Dict[str, Any]:
    return action("submit", value=value)


def task(
    task_id: str,
    instruction: str,
    success: str,
    files: Dict[str, str],
    rule: Dict[str, Any],
    *reference: Dict[str, Any],
) -> Task:
    return Task(task_id, instruction, success, files, [rule], list(reference))


